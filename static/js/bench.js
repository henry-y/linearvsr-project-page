const BENCH_METHODS = ["Real-ESRGAN", "RealBasicVSR", "RealViFormer", "UAV", "DOVE", "SeedVR2", "FlashVSR-Tiny", "SwiftVR", "LinearVSR"];
(function () {
  const tabs = document.getElementById('bench-tabs');
  const table = document.getElementById('bench-table');
  const names = Object.keys(BENCH);
  let cur = names[0];
  function render() {
    tabs.innerHTML = '';
    names.forEach((n) => {
      const b = document.createElement('button');
      b.textContent = n;
      b.className = n === cur ? 'on' : '';
      b.onclick = () => { cur = n; render(); };
      tabs.appendChild(b);
    });
    const last = BENCH_METHODS.length - 1;
    let h = '<thead><tr><th>Metric</th>' + BENCH_METHODS.map((m, i) => `<th class="${i === last ? 'ours' : ''}">${m}</th>`).join('') + '</tr></thead><tbody>';
    BENCH[cur].forEach(([metric, ...vals]) => {
      const up = metric.endsWith('↑');
      const distinct = [...new Set(vals.map(Number))].sort((a, b) => (up ? b - a : a - b));
      h += `<tr><td>${metric}</td>` + vals.map((v, i) => {
        const r = distinct.indexOf(Number(v)) + 1;
        return `<td class="${r <= 3 ? 'r' + r : ''} ${i === last ? 'ours' : ''}">${v}</td>`;
      }).join('') + '</tr>';
    });
    table.innerHTML = h + '</tbody>';
  }
  render();
})();
